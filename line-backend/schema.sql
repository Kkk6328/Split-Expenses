CREATE TABLE IF NOT EXISTS books(id TEXT PRIMARY KEY, owner TEXT NOT NULL, version INTEGER NOT NULL, data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS memberships(book_id TEXT NOT NULL, user_id TEXT NOT NULL, PRIMARY KEY(book_id,user_id));
CREATE INDEX IF NOT EXISTS member_user ON memberships(user_id);
CREATE TABLE IF NOT EXISTS invites(token TEXT PRIMARY KEY, book_id TEXT NOT NULL, revoked INTEGER NOT NULL DEFAULT 0);
